UPDATE atendimentos
SET atendente_id = CASE
    WHEN atendente_id IN ('11111111-1111-1111-1111-111111111112', '11111111-1111-1111-1111-111111111113') THEN '11111111-1111-1111-1111-111111111111'
    WHEN atendente_id IN ('22222222-2222-2222-2222-222222222222', '22222222-2222-2222-2222-222222222223') THEN '22222222-2222-2222-2222-222222222221'
    WHEN atendente_id IN ('33333333-3333-3333-3333-333333333332', '33333333-3333-3333-3333-333333333333') THEN '33333333-3333-3333-3333-333333333331'
    ELSE atendente_id
END
WHERE atendente_id IN (
    '11111111-1111-1111-1111-111111111112',
    '11111111-1111-1111-1111-111111111113',
    '22222222-2222-2222-2222-222222222222',
    '22222222-2222-2222-2222-222222222223',
    '33333333-3333-3333-3333-333333333332',
    '33333333-3333-3333-3333-333333333333'
);

WITH excedentes AS (
    SELECT id
    FROM (
        SELECT
            id,
            ROW_NUMBER() OVER (PARTITION BY atendente_id ORDER BY atribuido_em ASC NULLS LAST, criado_em ASC, id ASC) AS ordem
        FROM atendimentos
        WHERE status = 'EM_ATENDIMENTO'
          AND atendente_id IN (
              '11111111-1111-1111-1111-111111111111',
              '22222222-2222-2222-2222-222222222221',
              '33333333-3333-3333-3333-333333333331'
          )
    ) base
    WHERE ordem > 3
)
UPDATE atendimentos
SET status = 'AGUARDANDO',
    atendente_id = NULL,
    atribuido_em = NULL
WHERE id IN (SELECT id FROM excedentes);

UPDATE atendentes a
SET atendimentos_ativos = COALESCE((
    SELECT COUNT(*)
    FROM atendimentos at
    WHERE at.atendente_id = a.id
      AND at.status = 'EM_ATENDIMENTO'
), 0)
WHERE a.id IN (
    '11111111-1111-1111-1111-111111111111',
    '22222222-2222-2222-2222-222222222221',
    '33333333-3333-3333-3333-333333333331'
);

DELETE FROM atendentes
WHERE id IN (
    '11111111-1111-1111-1111-111111111112',
    '11111111-1111-1111-1111-111111111113',
    '22222222-2222-2222-2222-222222222222',
    '22222222-2222-2222-2222-222222222223',
    '33333333-3333-3333-3333-333333333332',
    '33333333-3333-3333-3333-333333333333'
);
